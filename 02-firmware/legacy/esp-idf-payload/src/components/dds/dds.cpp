void dds_configure(dds_oscillator_t *osc, uint32_t frequency_hz, uint32_t sample_rate_hz) {
    osc->phase_q16 = 0;
    osc->step_q16 = static_cast<uint32_t>((static_cast<uint64_t>(frequency_hz) * LUT_SIZE * 65536ULL) / sample_rate_hz);
}

int16_t dds_lookup_q15(uint8_t index) { return SINE_Q15[index]; }

int16_t dds_next_q15(dds_oscillator_t *osc) {
#if CONFIG_SEANERGY_NAIVE_TRIG
    constexpr float TWO_PI = 6.28318530718f;
    const float radians = (static_cast<float>(osc->phase_q16) / (LUT_SIZE * 65536.0f)) * TWO_PI;
    const int16_t value = static_cast<int16_t>(sinf(radians) * 32767.0f);
#else
    const int16_t value = SINE_Q15[(osc->phase_q16 >> 16U) & 0xFFU];
#endif
    osc->phase_q16 += osc->step_q16;
    return value;
}
